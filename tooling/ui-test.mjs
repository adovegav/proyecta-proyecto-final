import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { browser, login } from './browser.mjs';

const output = new URL('../artifacts/capturas/', import.meta.url);
await mkdir(output, { recursive: true });
const instance = await browser();
const context = await instance.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'es-BO' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const shot = name => page.screenshot({ path: fileURLToPath(new URL(`${name}.png`, output)), fullPage: true });
const name = `Proyecto QA ${Date.now()}`;
const taskName = `Tarea QA ${Date.now()}`;
try {
  await page.goto('http://localhost:5173/proyectos');
  await page.getByRole('heading', { name: /Tu próximo paso/ }).waitFor();
  await shot('01-login');
  await page.getByLabel('Correo electrónico').fill('demo@proyecta.local');
  await page.getByLabel('Contraseña', { exact: true }).fill('incorrecta');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Correo o contraseña incorrectos.' }).waitFor();
  await login(page);
  await shot('02-dashboard');
  await page.getByRole('link', { name: 'Nuevo proyecto', exact: true }).click();
  await page.getByLabel('Nombre del proyecto').fill(name);
  await page.getByLabel('Descripción', { exact: true }).fill('Creado durante la prueba de interfaz.');
  await shot('04-formulario-proyecto');
  await page.getByRole('button', { name: 'Crear proyecto', exact: true }).click();
  await page.getByRole('heading', { name, exact: true }).waitFor();
  await shot('03-proyectos');
  await page.getByRole('link', { name: `Editar ${name}`, exact: true }).click();
  await page.getByLabel('Estado').selectOption('planning');
  await page.getByRole('button', { name: 'Guardar cambios' }).click();
  await page.getByRole('status').filter({ hasText: 'Proyecto actualizado correctamente.' }).waitFor();
  await page.getByRole('link', { name: 'Tareas', exact: true }).click();
  await page.getByRole('link', { name: 'Nueva tarea', exact: true }).click();
  await page.getByLabel('Título de la tarea').fill(taskName);
  await page.getByLabel('Proyecto relacionado').selectOption({ label: name });
  await page.getByLabel('Prioridad').selectOption('high');
  await page.getByLabel('Fecha límite').fill('2026-12-15');
  await shot('06-formulario-tarea');
  await page.getByRole('button', { name: 'Crear tarea', exact: true }).click();
  await page.getByText(taskName, { exact: true }).waitFor();
  await shot('05-tareas');
  await page.getByRole('link', { name: `Editar ${taskName}`, exact: true }).click();
  await page.getByLabel('Estado').selectOption('completed');
  await page.getByRole('button', { name: 'Guardar cambios' }).click();
  await page.getByRole('status').filter({ hasText: 'Tarea actualizada correctamente.' }).waitFor();
  await page.getByRole('link', { name: 'Proyectos', exact: true }).click();
  await page.getByRole('button', { name: `Eliminar ${name}`, exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Eliminar', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'El proyecto tiene tareas relacionadas.' }).waitFor();
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.getByRole('link', { name: 'Tareas', exact: true }).click();
  await page.getByRole('button', { name: `Eliminar ${taskName}`, exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Eliminar', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Tarea eliminada correctamente.' }).waitFor();
  await page.getByRole('link', { name: 'Proyectos', exact: true }).click();
  await page.getByRole('button', { name: `Eliminar ${name}`, exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Eliminar', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Proyecto eliminado correctamente.' }).waitFor();
  await page.getByLabel('Buscar proyectos').fill('sin-resultados-qa');
  await page.getByRole('heading', { name: 'No encontramos proyectos' }).waitFor();
  await page.getByRole('link', { name: 'Resumen', exact: true }).click();
  await page.getByText('Próximas tareas', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Dashboard móvil sin desbordamiento horizontal');
  await shot('07-movil');
  await page.getByRole('link', { name: 'Tareas', exact: true }).click();
  await page.getByRole('heading', { name: 'Mis tareas.' }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Tabla contenida en scroll interno en móvil');
  await page.getByRole('button', { name: 'Cerrar sesión' }).click();
  await page.getByRole('heading', { name: /Tu próximo paso/ }).waitFor();
  assert.deepEqual(errors, [], 'Sin errores JavaScript');
  console.log('UI OK: seis pantallas, login, ambos CRUD, relación, conflicto 409, búsqueda, cierre de sesión y móvil.');
} finally { await context.close(); await instance.close(); }
